// ensureProjectContainerKeyPair returns the SSH key pair used to access the
// containers of a project, following the enterprise per-host naming convention
// (~/.ssh/id_rsa_<hostname>). Resolution order:
//
//  1. the host key pair recorded in the state db (generated by host.Build during
//     bootstrap) when both files exist on disk;
//  2. the key pair reference recorded for the host in cliconfig.yaml;
//  3. otherwise a freshly generated id_rsa_<hostname> pair under ~/.ssh.
//
// Whichever pair is resolved, its paths are persisted in cliconfig.yaml. The
// private key never leaves ~/.ssh and is never sent to the agent; only the
// public key is installed into the container's authorized_keys at deploy time.
func ensureProjectContainerKeyPair(projectName string) (pathToPrv, pathToPub string, err error) {
	hostName := projectAgentHost(projectName)

	if prv, pub, ok := existingKeyPair(db.GetHostKey(hostName), db.GetHostPubKey(hostName)); ok {
		return persistContainerKeyRef(hostName, prv, pub)
	}

	if prv, pub, ok := config.HostContainerSSHKey(hostName); ok {
		if prv, pub, stillThere := existingKeyPair(prv, pub); stillThere {
			return prv, pub, nil
		}
	}

	// Never overwrite a key we do not track (e.g. created by enterprise cds):
	// reuse a complete pair, refuse a half-present one.
	conventional := shexec.KeyPairPaths(hostName)
	if prv, pub, ok := existingKeyPair(conventional.PathToPrv, conventional.PathToPub); ok {
		return persistContainerKeyRef(hostName, prv, pub)
	}
	for _, path := range []string{conventional.PathToPrv, conventional.PathToPub} {
		if _, statErr := cos.Fs.Stat(path); statErr == nil {
			return cg.EmptyStr, cg.EmptyStr, cerr.NewError(fmt.Sprintf("Refusing to overwrite existing %s: the key pair is incomplete; move or complete it", path))
		}
	}

	clog.Info("No SSH key found to access containers; generating a host key pair")
	sshDir := filepath.Join(cenv.GetUserHomeDir(), ".ssh")
	if mkErr := cos.Fs.MkdirAll(sshDir, 0700); mkErr != nil {
		return cg.EmptyStr, cg.EmptyStr, cerr.AppendError("Failed to create ~/.ssh directory for container-access key", mkErr)
	}
	keyPair, genErr := shexec.GenerateKeyPair(hostName)
	if genErr != nil {
		return cg.EmptyStr, cg.EmptyStr, cerr.AppendError("Failed to generate a container-access SSH key pair", genErr)
	}
	return persistContainerKeyRef(hostName, keyPair.PathToPrv, keyPair.PathToPub)
}

// existingKeyPair returns the pair unchanged when both paths are non-empty and
// present on disk as regular files.
func existingKeyPair(prv, pub string) (string, string, bool) {
	if prv == cg.EmptyStr || pub == cg.EmptyStr {
		return cg.EmptyStr, cg.EmptyStr, false
	}
	if !isRegularFile(prv) || !isRegularFile(pub) {
		return cg.EmptyStr, cg.EmptyStr, false
	}
	return prv, pub, true
}

func isRegularFile(path string) bool {
	info, err := cos.Fs.Stat(path)
	return err == nil && info.Mode().IsRegular()
}

// persistContainerKeyRef records the key pair paths for hostName in
// cliconfig.yaml and returns them. A persistence failure is logged but does not
// block access, since the key material is already on disk.
func persistContainerKeyRef(hostName, prv, pub string) (string, string, error) {
	if err := config.SetHostContainerSSHKey(hostName, prv, pub); err != nil {
		clog.Warn("Failed to record container SSH key in CLI config", err)
	}
	return prv, pub, nil
}

// hostContainerIdentityFile returns the private key path recorded for hostName
// (cliconfig.yaml first, then the state db host key), or empty when none is
// known. It never generates a key — it is used when writing the managed
// ssh_config block, by which point deploy/ssh has already ensured the key.
func hostContainerIdentityFile(hostName string) string {
	if prv, _, ok := config.HostContainerSSHKey(hostName); ok {
		return prv
	}
	if prv, pub, ok := existingKeyPair(db.GetHostKey(hostName), db.GetHostPubKey(hostName)); ok {
		_ = pub
		return prv
	}
	return cg.EmptyStr
}
