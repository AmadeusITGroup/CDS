func TestAddComment(t *testing.T) {
	pubKeyBase := "ecdsa-sha2-nistp384 AAEEEDDD"
	myPubKeyBytes := []byte(pubKeyBase + "\n")
	result, err := addCdsWatermarkToPublicKey(myPubKeyBytes)
	if err != nil {
		t.Fatalf("Test failed because of %v", err)
	}
	resultStr := string(result)

	// Works for username@hostname and for AMAIISDOM\username@hostname; a
	// hostname may hold '-' and '.' (CI runner ip-10-0-137-251, mac.local)
	regexpStr := pubKeyBase + " generated by CDS: (\\w|\\\\)+@[\\w.-]+\\n"
	r := regexp.MustCompile(regexpStr)
	for _, host := range []string{"myhost", "ip-10-0-137-251", "mac.local"} {
		sample := pubKeyBase + " generated by CDS: AMAIISDOM\\runner@" + host + "\n"
		if !r.MatchString(sample) {
			t.Fatalf("%q was supposed to match %v", sample, regexpStr)
		}
	}
	if !r.MatchString(resultStr) {
		t.Fatalf("%v was supposed to match %v", resultStr, regexpStr)
	}
}

func TestCheckValidSSHKeyPairExistence(t *testing.T) {
	cos.SetMockedFileSystem()
	defer cos.SetRealFileSystem()

	currentWorkDir, err := getCurrentWorkingDir()
	if err != nil {
		t.Fatal(err)
	}
	mockedPublicKeyPath := filepath.Join(currentWorkDir, "mockedPublicKey")
	mockedPrivateKeyPath := filepath.Join(currentWorkDir, "mockedPrivateKey")

	h := mockedTarget{name: "mockedHost", pathToPub: mockedPublicKeyPath, pathToPrv: mockedPrivateKeyPath}

	expectedError := cerr.NewError(fmt.Sprintf("Host %s does not have a valid ssh key pair", h.FQDN()))
	// Both private and public ssh keys are missing
	assert.Error(t, CheckValidSSHKeyPairExistence(h))
	assert.Equal(t, cerr.Message(CheckValidSSHKeyPairExistence(h)), cerr.Message(expectedError))

	// Missing private ssh key
	if _, err := cos.Fs.OpenFile(mockedPublicKeyPath, os.O_CREATE|os.O_RDWR, fs.FileMode(0600)); err != nil {
		t.Fatal(err)
	}
	assert.Error(t, CheckValidSSHKeyPairExistence(h))
	assert.Equal(t, cerr.Message(CheckValidSSHKeyPairExistence(h)), cerr.Message(expectedError))

	if err := cos.Fs.Remove(mockedPublicKeyPath); err != nil {
		t.Fatal(err)
	}

	// Missing public ssh key
	if _, err := cos.Fs.OpenFile(mockedPrivateKeyPath, os.O_CREATE|os.O_RDWR, fs.FileMode(0600)); err != nil {
		t.Fatal(err)
	}
	assert.Error(t, CheckValidSSHKeyPairExistence(h))
	assert.Equal(t, cerr.Message(CheckValidSSHKeyPairExistence(h)), cerr.Message(expectedError))

	//Both keys are present
	if _, err := cos.Fs.OpenFile(mockedPublicKeyPath, os.O_CREATE|os.O_RDWR, fs.FileMode(0600)); err != nil {
		t.Fatal(err)
	}
	assert.NoError(t, CheckValidSSHKeyPairExistence(h))
	assert.Equal(t, CheckValidSSHKeyPairExistence(h), nil)
}

// EnsureKeyPair must never overwrite an existing key file, even
// through a symlink, and must reuse a complete pair unchanged.
func TestEnsureKeyPairNeverOverwrites(t *testing.T) {
	cos.SetRealFileSystem()
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("USERPROFILE", home)
	sshDir := filepath.Join(home, ".ssh")
	if err := os.MkdirAll(sshDir, 0700); err != nil {
		t.Fatal(err)
	}
	read := func(p string) string { b, _ := os.ReadFile(p); return string(b) }

	// Fresh: a pair is generated.
	fresh, err := EnsureKeyPair("fresh")
	assert.NoError(t, err)
	assert.Contains(t, read(fresh.PathToPrv), "PRIVATE KEY")
	assert.Contains(t, read(fresh.PathToPub), "generated by CDS")

	// Complete pair: reused unchanged.
	pair := KeyPairPaths("full")
	assert.NoError(t, os.WriteFile(pair.PathToPrv, []byte("PRV"), 0600))
	assert.NoError(t, os.WriteFile(pair.PathToPub, []byte("PUB"), 0644))
	got, err := EnsureKeyPair("full")
	assert.NoError(t, err)
	assert.Equal(t, pair, got)
	assert.Equal(t, "PRV", read(pair.PathToPrv))
	assert.Equal(t, "PUB", read(pair.PathToPub))

	// Half pairs: refused, existing file untouched, nothing created.
	half := KeyPairPaths("onlyprv")
	assert.NoError(t, os.WriteFile(half.PathToPrv, []byte("PRV"), 0600))
	_, err = EnsureKeyPair("onlyprv")
	assert.Error(t, err)
	assert.Equal(t, "PRV", read(half.PathToPrv))
	assert.NoFileExists(t, half.PathToPub)

	half = KeyPairPaths("onlypub")
	assert.NoError(t, os.WriteFile(half.PathToPub, []byte("PUB"), 0644))
	_, err = EnsureKeyPair("onlypub")
	assert.Error(t, err)
	assert.Equal(t, "PUB", read(half.PathToPub))
	assert.NoFileExists(t, half.PathToPrv)

	if runtime.GOOS == "windows" {
		return // symlinks need privileges on Windows
	}
	// Symlinked complete pair (a past regression): reused, target untouched.
	target := t.TempDir()
	link := KeyPairPaths("linked")
	assert.NoError(t, os.WriteFile(filepath.Join(target, "k"), []byte("REALPRV"), 0600))
	assert.NoError(t, os.WriteFile(filepath.Join(target, "k.pub"), []byte("REALPUB"), 0644))
	assert.NoError(t, os.Symlink(filepath.Join(target, "k"), link.PathToPrv))
	assert.NoError(t, os.Symlink(filepath.Join(target, "k.pub"), link.PathToPub))
	_, err = EnsureKeyPair("linked")
	assert.NoError(t, err)
	assert.Equal(t, "REALPRV", read(filepath.Join(target, "k")))
	assert.Equal(t, "REALPUB", read(filepath.Join(target, "k.pub")))

	// Dangling symlink: refused, its target is not created.
	dangling := KeyPairPaths("dangling")
	assert.NoError(t, os.Symlink(filepath.Join(target, "missing"), dangling.PathToPrv))
	_, err = EnsureKeyPair("dangling")
	assert.Error(t, err)
	assert.NoFileExists(t, filepath.Join(target, "missing"))
	assert.NoFileExists(t, dangling.PathToPub)
}

// a suffix that would leave $HOME/.ssh (separator or "..") is
// refused and nothing is written.
func TestEnsureKeyPairRejectsPathSuffix(t *testing.T) {
	cos.SetRealFileSystem()
	home := t.TempDir()
	t.Setenv("HOME", home)
	t.Setenv("USERPROFILE", home)
	if err := os.MkdirAll(filepath.Join(home, ".ssh"), 0700); err != nil {
		t.Fatal(err)
	}
	for _, suffix := range []string{"", "../../../x", "../x", "a/b", `a\b`, ".."} {
		_, err := EnsureKeyPair(suffix)
		assert.Error(t, err, suffix)
	}
	assert.NoFileExists(t, filepath.Join(home, "x"))
	assert.NoFileExists(t, filepath.Join(home, "id_rsa_x"))
	entries, _ := os.ReadDir(filepath.Join(home, ".ssh"))
	assert.Empty(t, entries)

	// a dotted host name is still fine
	_, err := EnsureKeyPair("host.example.com")
	assert.NoError(t, err)
}
